#!/usr/bin/env python3
"""Franciscan Health Bourbon Dinner (11/19/2026) photos -> build/5j-data-bourbon-img.js

Usage:  python3 -I mkbourbon.py <folder with the original photos>

Writes `const BOURBON_IMG = {key: "data:image/jpeg;base64,..."}`. The app is one
self-contained file, so the photos are embedded, sized for a phone (720px long side).
The words live by hand in build/5j-data-bourbon.js; this script only does pictures.
"""
import base64, io, pathlib, sys
from PIL import Image, ImageOps

SRC = pathlib.Path(sys.argv[1])
OUT = pathlib.Path(__file__).resolve().parent / "build" / "5j-data-bourbon-img.js"
PX, Q = 720, 68
# key -> (file name ending, crop box on the upright original or None)
SHOTS = {
    "overview": ("IMG_1424.jpeg", None),
    "soup":     ("IMG_1429.jpeg", None),
    "mac":      ("IMG_1427.jpeg", None),
    "salmon":   ("IMG_1428.jpeg", None),
    "filet":    ("IMG_1426.jpeg", None),
    "crepes":   ("IMG_1425.jpeg", None),
    "prep":     ("IMG_1430.jpeg", None),
    # the printed card shows two copies side by side; keep the left one so the text reads
    "menu":     ("menu.jpg", (225, 265, 780, 1760)),
}
out = {}
for key, (end, box) in SHOTS.items():
    f = next(p for p in SRC.iterdir() if p.name.endswith(end))
    im = ImageOps.exif_transpose(Image.open(f)).convert("RGB")
    if box: im = im.crop(box)
    long_px = PX if key != "menu" else 1000
    im.thumbnail((long_px, long_px), Image.LANCZOS)
    buf = io.BytesIO(); im.save(buf, "JPEG", quality=Q, optimize=True, progressive=True)
    out[key] = "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()
    print(f"{key:9s} {im.size} {len(buf.getvalue())//1024} KB")
OUT.write_text("/* GENERATED by mkbourbon.py — do not hand-edit. */\nconst BOURBON_IMG = {\n" +
    ",\n".join(f'  {k}: "{v}"' for k, v in out.items()) + "\n};\n")
print(f"wrote {OUT} ({OUT.stat().st_size:,} bytes)")
